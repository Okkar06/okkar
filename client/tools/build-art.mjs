// =====================================================================
//  BUILD ART — turns the sprite code in tools/art/*.mjs into images.
//
//  Run:  npm run art        (from the client folder)
//
//  Output:
//    public/assets/atlas/decor.png + decor.json   all sprites, one atlas
//    public/assets/tilesets/extras.png            16x16 tiles for Tiled
//    src/theme/tileIds.js                         tile name -> number
//
//  Every colour comes from src/theme/palette.js (see the
//  pixel-art-direction skill). Edit a sprite, run `npm run art`, refresh.
// =====================================================================

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { encodePng } from './lib/png.mjs'
import { PixelCanvas } from './lib/PixelCanvas.mjs'
import * as fx from './art/fx.mjs'
import * as nature from './art/nature.mjs'
import * as exterior from './art/exterior.mjs'
import * as interior from './art/interior.mjs'
import * as water from './art/water.mjs'
import * as tiles from './art/tiles.mjs'
import * as characters from './art/characters.mjs'

const clientDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..')
const ATLAS_WIDTH = 256
const PADDING = 1 // empty pixels between sprites so they never bleed into each other
const TILESET_COLUMNS = 8

// ---------------------------------------------------------------------
//  1. Collect every sprite and tile
// ---------------------------------------------------------------------
const spriteModules = [fx, nature, exterior, interior, water]
const sprites = []
for (let i = 0; i < spriteModules.length; i++) {
  const list = spriteModules[i].sprites()
  for (let j = 0; j < list.length; j++) sprites.push(list[j])
}
const tileList = tiles.tiles().concat(interior.tiles(), water.tiles())

// ---------------------------------------------------------------------
//  2. Pack sprites into one atlas ("shelf packing": tallest first,
//     left to right, start a new row when the current one is full)
// ---------------------------------------------------------------------
const sorted = sprites.slice().sort(function (a, b) {
  return b.canvas.height - a.canvas.height
})
const frames = {}
let cursorX = PADDING
let cursorY = PADDING
let rowHeight = 0
const placements = []
for (let i = 0; i < sorted.length; i++) {
  const sprite = sorted[i]
  const w = sprite.canvas.width
  const h = sprite.canvas.height
  if (cursorX + w + PADDING > ATLAS_WIDTH) {
    cursorX = PADDING
    cursorY = cursorY + rowHeight + PADDING
    rowHeight = 0
  }
  if (frames[sprite.name]) throw new Error('Duplicate sprite name: ' + sprite.name)
  placements.push({ sprite: sprite, x: cursorX, y: cursorY })
  frames[sprite.name] = {
    frame: { x: cursorX, y: cursorY, w: w, h: h },
    rotated: false,
    trimmed: false,
    spriteSourceSize: { x: 0, y: 0, w: w, h: h },
    sourceSize: { w: w, h: h },
  }
  cursorX = cursorX + w + PADDING
  rowHeight = Math.max(rowHeight, h)
}
const atlasHeight = cursorY + rowHeight + PADDING
const atlas = new PixelCanvas(ATLAS_WIDTH, atlasHeight)
for (let i = 0; i < placements.length; i++) {
  atlas.blit(placements[i].sprite.canvas, placements[i].x, placements[i].y)
}

const atlasDir = path.join(clientDir, 'public', 'assets', 'atlas')
fs.mkdirSync(atlasDir, { recursive: true })
fs.writeFileSync(path.join(atlasDir, 'decor.png'), encodePng(atlas.width, atlas.height, atlas.data))
fs.writeFileSync(
  path.join(atlasDir, 'decor.json'),
  JSON.stringify({ frames: frames, meta: { image: 'decor.png', size: { w: atlas.width, h: atlas.height }, scale: '1' } })
)

// ---------------------------------------------------------------------
//  3. Lay the 16x16 tiles out in a grid (a tileset Tiled can use)
// ---------------------------------------------------------------------
const rows = Math.max(1, Math.ceil(tileList.length / TILESET_COLUMNS))
const tileset = new PixelCanvas(TILESET_COLUMNS * 16, rows * 16)
const tileIds = {}
for (let i = 0; i < tileList.length; i++) {
  const t = tileList[i]
  if (t.canvas.width !== 16 || t.canvas.height !== 16) throw new Error('Tile must be 16x16: ' + t.name)
  if (tileIds[t.name] !== undefined) throw new Error('Duplicate tile name: ' + t.name)
  tileIds[t.name] = i
  tileset.blit(t.canvas, (i % TILESET_COLUMNS) * 16, Math.floor(i / TILESET_COLUMNS) * 16)
}
fs.writeFileSync(
  path.join(clientDir, 'public', 'assets', 'tilesets', 'extras.png'),
  encodePng(tileset.width, tileset.height, tileset.data)
)

// Which tiles are solid (used by the starter-map generator for Tiled properties).
const solidTiles = []
for (let i = 0; i < tileList.length; i++) {
  if (tileList[i].solid) solidTiles.push(tileList[i].name)
}

const moduleText =
  '// GENERATED by tools/build-art.mjs — do not edit by hand (run `npm run art`).\n' +
  '// Tile numbers inside public/assets/tilesets/extras.png (0 = top-left).\n\n' +
  'export const EXTRAS_COLUMNS = ' + TILESET_COLUMNS + '\n\n' +
  'export const EXTRAS = ' + JSON.stringify(tileIds, null, 2) + '\n\n' +
  'export const EXTRAS_SOLID = ' + JSON.stringify(solidTiles) + '\n'
fs.writeFileSync(path.join(clientDir, 'src', 'theme', 'tileIds.js'), moduleText)

// ---------------------------------------------------------------------
//  4. Character sprite sheets (player and Pip): their own PNGs, because
//     Phaser loads them as spritesheets with fixed-size frames.
// ---------------------------------------------------------------------
const characterSheets = characters.sheets()
for (let i = 0; i < characterSheets.length; i++) {
  const sheetInfo = characterSheets[i]
  const frameW = sheetInfo.frames[0].width
  const frameH = sheetInfo.frames[0].height
  const rowsOfFrames = Math.ceil(sheetInfo.frames.length / sheetInfo.columns)
  const out = new PixelCanvas(frameW * sheetInfo.columns, frameH * rowsOfFrames)
  for (let f = 0; f < sheetInfo.frames.length; f++) {
    out.blit(sheetInfo.frames[f], (f % sheetInfo.columns) * frameW, Math.floor(f / sheetInfo.columns) * frameH)
  }
  fs.writeFileSync(path.join(clientDir, 'public', 'assets', 'sprites', sheetInfo.file), encodePng(out.width, out.height, out.data))
}

console.log(
  'Atlas: ' + sprites.length + ' sprites, ' + atlas.width + 'x' + atlas.height + ' px. ' +
  'Tileset: ' + tileList.length + ' tiles, ' + tileset.width + 'x' + tileset.height + ' px.'
)
